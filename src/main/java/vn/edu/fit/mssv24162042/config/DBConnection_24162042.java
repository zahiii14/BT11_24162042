    public static Connection getConnection() throws Exception {
        // Try SQL Server TCP first with 2s login timeout
        DriverManager.setLoginTimeout(2);
        try {
            Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
            String sqlServerUrl = "jdbc:sqlserver://localhost:1433;databaseName=" + DB_NAME 
                    + ";encrypt=false;trustServerCertificate=true;loginTimeout=2;";
            Connection conn = DriverManager.getConnection(sqlServerUrl);
            if (conn != null && !conn.isClosed()) {
                return conn;
            }
        } catch (Exception ignored) {
            // TCP/IP disabled or timeout -> fallback to embedded H2 database
        }

        // Fast, reliable embedded H2 connection (MSSQLServer mode)
        Class.forName("org.h2.Driver");
        String h2Url = "jdbc:h2:file:./target/WebDB_24162042;MODE=MSSQLServer;AUTO_SERVER=TRUE;DB_CLOSE_DELAY=-1";
        Connection h2Conn = DriverManager.getConnection(h2Url, "sa", "");

        if (!h2Initialized) {
            synchronized (DBConnection_24162042.class) {
                if (!h2Initialized) {
                    initH2Database(h2Conn);
                    h2Initialized = true;
                }
            }
        }

        return h2Conn;
    }

